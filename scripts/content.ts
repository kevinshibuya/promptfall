// Builds .claude/skills/promptfall-content/reference/content.md from the sim's content registry. A
// pure function of the sim: `pnpm content:check` fails CI when the committed reference is stale.
//
// tsx scripts/content.ts
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { type BossMove, baseTier, type Content, dropTier, LADDER_END } from '@promptfall/sim'

/** A table cell: pipes escaped so a glyph like `|` stays in its column. */
const cell = (s: string | number) => String(s).replaceAll('|', '\\|')
const code = (s: string) => `\`${cell(s)}\``
/** `×3.5`: a multiplier in basis points. */
const times = (bp: number) => `×${bp / 10000}`

/** A zone boss's move in the combat log's words. */
const MOVE_WORDS: Record<BossMove, string> = {
  strike_twice: 'strikes twice',
  heal_self: 'heals itself',
  hit_all: 'hits the whole party',
  rage: 'rages under half HP',
}

function table(head: string[], rows: (string | number)[][]): string[] {
  return [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ]
}

/** The reference as Markdown: one table per registry, in the registry's own order. */
export function contentReference(c: Content): string {
  const name = (id: string) => cell(c.enemies[id]?.name ?? id)
  return [
    '# Promptfall content',
    '',
    "Generated by `pnpm content` (`scripts/content.ts`) from the sim's `content` export. Change the sim, then regenerate.",
    '',
    '## Zones',
    '',
    ...table(
      ['Index', 'Name', 'Enemies', 'Boss', 'Turn boss'],
      c.zones.map((z) => [
        z.index,
        cell(z.name),
        z.enemies.map(name).join(', '),
        name(z.boss),
        name(z.turnBoss),
      ]),
    ),
    '',
    '## Tiers',
    '',
    'The ladder runs the twelve zones once per tier, as one running zone number: zone 13 is tier 2,',
    "zone 1, with zone 1's enemies at their tier's numbers. Past tier 1 every base drops, at zone",
    "12's rarity odds.",
    '',
    ...table(
      ['Tier', 'Zones', 'Item tier dropped'],
      Array.from({ length: Math.ceil(LADDER_END / c.zones.length) }, (_, i) => {
        const first = i * c.zones.length + 1
        const last = Math.min(LADDER_END, first + c.zones.length - 1)
        const drops = i === 0 ? 'the base’s, 1 to 4' : dropTier(first, '')
        return [i + 1, `${first} to ${last}`, drops]
      }),
    ),
    '',
    '## Enemies and bosses',
    '',
    ...table(
      ['Id', 'Name', 'Archetype', 'Move'],
      Object.values(c.enemies).map((e) => [
        code(e.id),
        cell(e.name),
        e.archetype,
        e.move ? MOVE_WORDS[e.move] : '',
      ]),
    ),
    '',
    '## Item bases',
    '',
    ...table(
      ['Id', 'Name', 'Glyph', 'Slot', 'Min zone', 'Tier'],
      Object.values(c.itemBases).map((i) => [
        code(i.id),
        cell(i.name),
        code(i.glyph),
        i.slot,
        i.minZone,
        baseTier(i.id),
      ]),
    ),
    '',
    '## Item tiers',
    '',
    "An item's tier multiplies its affixes' rolls and its reforge price.",
    '',
    ...table(
      ['Tier', 'Multiplier'],
      c.itemTierMultBp.map((bp, i) => [i + 1, times(bp)]),
    ),
    '',
    '## Hero templates',
    '',
    ...table(
      ['Id', 'Name', 'Class'],
      Object.values(c.heroTemplates).map((h) => [code(h.id), cell(h.name), h.cls]),
    ),
    '',
    '## Rarities',
    '',
    "The tavern's odds, and its guarantee: a recruit of the rarity or better within that many recruits.",
    '',
    ...table(
      ['Rarity', 'Level cap', 'Tavern odds', 'Tavern guarantee'],
      Object.entries(c.rarity).map(([r, rule]) => {
        const rarity = r as keyof Content['tavern']['odds']
        const within = (c.tavern.guarantees as Partial<Record<string, number>>)[r]
        return [r, rule.levelCap, `${c.tavern.odds[rarity] / 100}%`, within ?? '—']
      }),
    ),
    '',
    '## Achievements',
    '',
    'Paid by the ledger once per step, with reason `achievement:<id>:<step>`; steps count from 1.',
    '',
    ...table(
      ['Id', 'Name', 'Reads', 'Steps'],
      c.achievements.map((a) => [
        code(a.id),
        cell(a.name),
        a.reads,
        a.steps
          .map((s) => `${s.at.toLocaleString('en-US')} (${s.gold.toLocaleString('en-US')} gold)`)
          .join(', '),
      ]),
    ),
    '',
    '## Daily goals',
    '',
    "One row a day per account, its target `base + step × ⌊(zone − 1) / every⌋` at the day's first",
    "commit. Met, it pays the zone's wave gold midpoint × 300 with reason `goal:<day>`.",
    '',
    ...table(
      ['Kind', 'Base', 'Step', 'Every (zones)'],
      c.goals.map((g) => [g.kind, g.base, g.step, g.everyZones]),
    ),
    '',
    '## Weekly hunts',
    '',
    "One row a week in turn, by the week's index from the epoch, counted by the ledger from every",
    "account's commits but bots'. At the week's close each contributor at 0.5% of the target or",
    'more gets one reward roll at its zone, the target reached or not.',
    '',
    ...table(
      ['Id', 'Name', 'Counts', 'Target'],
      c.hunts.map((h) => [code(h.id), cell(h.name), h.kind, h.target.toLocaleString('en-US')]),
    ),
    '',
  ].join('\n')
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  const { content } = await import('@promptfall/sim')
  const out = join(import.meta.dirname, '../.claude/skills/promptfall-content/reference/content.md')
  writeFileSync(out, contentReference(content))
  console.log(
    `${out}: ${content.zones.length} zones, ${Object.keys(content.enemies).length} enemies`,
  )
}
