// Writes plugins/promptfall/hooks/stage/goldens/: the golden hashes of each stage scenario and an
// .svg of each for eyeballing. Run it only when a scenario's drawing is meant to change, and say
// so in the commit message: `tsx scripts/stage-goldens.ts`.
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Frame } from '../plugins/promptfall/hooks/stage/compose'
import {
  goldenOf,
  PANE_SCENARIOS,
  pane,
  paneGoldenOf,
  paneSvgOf,
  SCENARIOS,
  STRIP_SCENARIOS,
  scenePicture,
  stage,
  strip,
  stripGoldenOf,
  stripPicture,
  stripSvgOf,
  svgOf,
} from '../plugins/promptfall/hooks/stage/scenarios'
import { writePng } from './png'

const OUT = join(import.meta.dirname, '../plugins/promptfall/hooks/stage/goldens')
mkdirSync(OUT, { recursive: true })
const lines = [
  '// Generated by scripts/stage-goldens.ts. Do not edit: run `pnpm stage:goldens`.',
  'import type {',
  '  Golden,',
  '  PaneGolden,',
  '  PaneScenario,',
  '  Scenario,',
  '  StripGolden,',
  '  StripScenario,',
  "} from '../scenarios'",
  '',
  'export const GOLDENS: Record<Scenario, Golden> = {',
]
for (const name of SCENARIOS) {
  const s = stage(name)
  const g = goldenOf(s)
  lines.push(
    `  ${name}: ${JSON.stringify(g)
      .replace(/"(\w+)":/g, '$1: ')
      .replace(/,/g, ', ')},`,
  )
  writeFileSync(join(OUT, `${name}.svg`), `${svgOf(s)}\n`)
}
lines.push('}', '', 'export const STRIP_GOLDENS: Record<StripScenario, StripGolden> = {')
// A strip's or pane's PNG lays its windows on a dark terminal background, to be looked at.
const BG = [0x1e, 0x1e, 0x24]
function png(name: string, pic: Frame): void {
  const scale = 2
  const data = new Uint8Array(pic.width * scale * pic.height * scale * 4)
  for (let y = 0; y < pic.height * scale; y++) {
    for (let x = 0; x < pic.width * scale; x++) {
      const si = (Math.floor(y / scale) * pic.width + Math.floor(x / scale)) * 4
      const di = (y * pic.width * scale + x) * 4
      const on = (pic.rgba[si + 3] ?? 0) > 0
      data[di] = on ? (pic.rgba[si] ?? 0) : (BG[0] ?? 0)
      data[di + 1] = on ? (pic.rgba[si + 1] ?? 0) : (BG[1] ?? 0)
      data[di + 2] = on ? (pic.rgba[si + 2] ?? 0) : (BG[2] ?? 0)
      data[di + 3] = 255
    }
  }
  writePng(join(OUT, `${name}.png`), { width: pic.width * scale, height: pic.height * scale, data })
}
for (const name of STRIP_SCENARIOS) {
  const input = strip(name)
  const g = stripGoldenOf(input)
  lines.push(
    `  '${name}': ${JSON.stringify(g)
      .replace(/"(\w+)":/g, '$1: ')
      .replace(/,/g, ', ')},`,
  )
  writeFileSync(join(OUT, `${name}.svg`), `${stripSvgOf(input)}\n`)
  png(name, stripPicture(input))
}
lines.push('}', '', 'export const PANE_GOLDENS: Record<PaneScenario, PaneGolden> = {')
for (const name of PANE_SCENARIOS) {
  const build = pane(name)
  const g = paneGoldenOf(build)
  lines.push(
    `  '${name}': ${JSON.stringify(g)
      .replace(/"(\w+)":/g, '$1: ')
      .replace(/,/g, ', ')},`,
  )
  writeFileSync(join(OUT, `${name}.svg`), `${paneSvgOf(build)}\n`)
  png(name, scenePicture(build.scene))
}
lines.push('}', '')
writeFileSync(join(OUT, 'index.ts'), lines.join('\n'))
console.log(
  `${OUT}: ${SCENARIOS.length} stage, ${STRIP_SCENARIOS.length} strip and ${PANE_SCENARIOS.length} pane scenarios`,
)
