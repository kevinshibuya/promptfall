// Writes plugins/promptfall/hooks/stage/goldens/: the golden hashes of each stage scenario, and an
// .svg and a Raster .png of each stage and band scenario for eyeballing. Run it only when a scenario's drawing is meant to change, and say
// so in the commit message: `tsx scripts/stage-goldens.ts`.
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Frame } from '../plugins/promptfall/hooks/stage/compose'
import {
  BAND_SCENARIOS,
  band,
  bandDesktopSvgOf,
  bandGoldenOf,
  bandPicture,
  bandSvgOf,
  cellsPicture,
  goldenOf,
  PANE_SCENARIOS,
  pane,
  paneGoldenOf,
  paneSvgOf,
  renders,
  SCENARIOS,
  STRIP_SCENARIOS,
  scenePicture,
  stage,
  strip,
  stripGoldenOf,
  stripPicture,
  stripSvgOf,
} from '../plugins/promptfall/hooks/stage/scenarios'
import { writePng } from './png'

const OUT = join(import.meta.dirname, '../plugins/promptfall/hooks/stage/goldens')
mkdirSync(OUT, { recursive: true })
const lines = [
  '// Generated by scripts/stage-goldens.ts. Do not edit: run `pnpm stage:goldens`.',
  'import type {',
  '  BandGolden,',
  '  BandScenario,',
  '  Golden,',
  '  PaneGolden,',
  '  PaneScenario,',
  '  Scenario,',
  '  StripGolden,',
  '  StripScenario,',
  "} from '../scenarios'",
  '',
  'export const GOLDENS: Record<Scenario, Golden> = {',
]
// A stage's Raster, strip's or pane's PNG lays its pixels on a dark terminal background, to be looked at.
const BG = [0x1e, 0x1e, 0x24]
function png(name: string, pic: Frame, scale = 2): void {
  const data = new Uint8Array(pic.width * scale * pic.height * scale * 4)
  for (let y = 0; y < pic.height * scale; y++) {
    for (let x = 0; x < pic.width * scale; x++) {
      const si = (Math.floor(y / scale) * pic.width + Math.floor(x / scale)) * 4
      const di = (y * pic.width * scale + x) * 4
      const on = (pic.rgba[si + 3] ?? 0) > 0
      data[di] = on ? (pic.rgba[si] ?? 0) : (BG[0] ?? 0)
      data[di + 1] = on ? (pic.rgba[si + 1] ?? 0) : (BG[1] ?? 0)
      data[di + 2] = on ? (pic.rgba[si + 2] ?? 0) : (BG[2] ?? 0)
      data[di + 3] = 255
    }
  }
  writePng(join(OUT, `${name}.png`), { width: pic.width * scale, height: pic.height * scale, data })
}
for (const name of SCENARIOS) {
  const s = stage(name)
  const r = renders(s)
  const g = goldenOf(r)
  lines.push(
    `  ${/^\w+$/.test(name) ? name : `'${name}'`}: ${JSON.stringify(g)
      .replace(/"(\w+)":/g, '$1: ')
      .replace(/,/g, ', ')},`,
  )
  writeFileSync(join(OUT, `${name}.svg`), `${r.svg}\n`)
  // The Raster's cells as the terminal draws them: one cell CELL_W × CELL_H, numbers as glyphs.
  png(`${name}.raster`, cellsPicture(r.cells, s.model.box.columns), 1)
}
lines.push('}', '', 'export const STRIP_GOLDENS: Record<StripScenario, StripGolden> = {')
for (const name of STRIP_SCENARIOS) {
  const input = strip(name)
  const g = stripGoldenOf(input)
  lines.push(
    `  '${name}': ${JSON.stringify(g)
      .replace(/"(\w+)":/g, '$1: ')
      .replace(/,/g, ', ')},`,
  )
  writeFileSync(join(OUT, `${name}.svg`), `${stripSvgOf(input)}\n`)
  png(name, stripPicture(input))
}
lines.push('}', '', 'export const PANE_GOLDENS: Record<PaneScenario, PaneGolden> = {')
for (const name of PANE_SCENARIOS) {
  const build = pane(name)
  const g = paneGoldenOf(build)
  lines.push(
    `  '${name}': ${JSON.stringify(g)
      .replace(/"(\w+)":/g, '$1: ')
      .replace(/,/g, ', ')},`,
  )
  writeFileSync(join(OUT, `${name}.svg`), `${paneSvgOf(build)}\n`)
  png(name, scenePicture(build.scene))
}
lines.push('}', '', 'export const BAND_GOLDENS: Record<BandScenario, BandGolden> = {')
for (const name of BAND_SCENARIOS) {
  const input = band(name)
  const g = bandGoldenOf(input)
  lines.push(
    `  '${name}': ${JSON.stringify(g)
      .replace(/"(\w+)":/g, '$1: ')
      .replace(/,/g, ', ')},`,
  )
  writeFileSync(join(OUT, `${name}.svg`), `${bandSvgOf(input)}\n`)
  writeFileSync(join(OUT, `${name}.desktop.svg`), `${bandDesktopSvgOf(input)}\n`)
  png(name, bandPicture(input))
  // The Raster's band as the terminal draws it, laid out as play lays it out.
  png(`${name}.raster`, cellsPicture(input.cells, input.rasterBox.columns), 1)
}
lines.push('}', '')
writeFileSync(join(OUT, 'index.ts'), lines.join('\n'))
console.log(
  `${OUT}: ${SCENARIOS.length} stage, ${STRIP_SCENARIOS.length} strip, ${PANE_SCENARIOS.length} pane and ${BAND_SCENARIOS.length} band scenarios`,
)
