// Bundles @promptfall/sim, @promptfall/protocol and @promptfall/ledger into the plugin folder.
// A mod imports only files inside its own folder, so the bundles are committed.
import { readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'tsup'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const plugin = join(root, 'plugins/promptfall')
const vendor = join(plugin, 'hooks/vendor')
const tsconfig = join(root, 'scripts/tsconfig.vendor.json')

rmSync(vendor, { recursive: true, force: true })

const common = {
  format: ['esm'],
  outDir: vendor,
  splitting: false,
  minify: false,
  sourcemap: false,
  clean: false,
  target: 'es2022',
  platform: 'neutral',
  silent: true,
  tsconfig,
  esbuildOptions(options) {
    options.mainFields = ['module', 'main']
    options.conditions = ['import', 'module', 'default']
  },
}

await build({
  ...common,
  entry: { sim: join(root, 'packages/sim/src/index.ts') },
  dts: true,
})

await build({
  ...common,
  entry: { protocol: join(root, 'packages/protocol/src/index.ts') },
  external: ['@promptfall/sim'],
  noExternal: ['zod'],
  dts: { resolve: true },
})

// zod is bundled into protocol.js, but its declarations cannot follow it into
// the plugin folder: the schemas are typed by the part of zod a plugin may use.
const ZOD_STANDIN = `declare namespace z {
  type SafeParse<T> = { success: true; data: T } | { success: false; error: Error }
  interface ZodType<T> {
    parse(value: unknown): T
    safeParse(value: unknown): SafeParse<T>
  }
  type ZodString = ZodType<string>
}`
{
  const path = join(vendor, 'protocol.d.ts')
  const text = readFileSync(path, 'utf8')
  if (!text.includes(`import { z } from 'zod';`))
    throw new Error('protocol.d.ts: zod import not found')
  writeFileSync(path, text.replace(`import { z } from 'zod';`, ZOD_STANDIN))
}

// The in-process host: the plugin runs the ledger itself when no server URL is set.
await build({
  ...common,
  entry: { ledger: join(root, 'packages/ledger/src/index.ts') },
  external: ['@promptfall/sim', '@promptfall/protocol'],
  dts: true,
})

for (const file of ['protocol.js', 'protocol.d.ts', 'ledger.js', 'ledger.d.ts']) {
  const path = join(vendor, file)
  const text = readFileSync(path, 'utf8')
    .replaceAll(`'@promptfall/sim'`, `'./sim.js'`)
    .replaceAll(`"@promptfall/sim"`, `'./sim.js'`)
    .replaceAll(`'@promptfall/protocol'`, `'./protocol.js'`)
    .replaceAll(`"@promptfall/protocol"`, `'./protocol.js'`)
  writeFileSync(path, text)
}

// zlib for the stage's PNG frames (hooks/stage/png.ts): fflate's zlibSync alone, tree-shaken.
await build({
  ...common,
  entry: { fflate: join(root, 'scripts/fflate-entry.ts') },
  noExternal: ['fflate'],
  dts: { resolve: true },
})

const BUNDLES = ['sim', 'protocol', 'ledger'].flatMap((name) => [`${name}.js`, `${name}.d.ts`])
for (const file of BUNDLES) {
  const text = readFileSync(join(vendor, file), 'utf8')
  if (text.includes('vitest'))
    throw new Error(`${file} mentions vitest: the contract suite leaked into the bundle`)
  if (text.includes('@promptfall/')) throw new Error(`${file} still imports a workspace package`)
  if (/from ['"]zod['"]/.test(text)) throw new Error(`${file} still imports zod`)
}

// The mod runtime has no platform globals; the query strings are built by hand.
for (const file of ['protocol.js', 'ledger.js']) {
  const text = readFileSync(join(vendor, file), 'utf8')
  if (text.includes('URLSearchParams')) throw new Error(`${file} uses URLSearchParams`)
}

const manifest = JSON.parse(readFileSync(join(plugin, '.claude-plugin/plugin.json'), 'utf8'))
writeFileSync(
  join(plugin, 'hooks/version.ts'),
  `// Generated by scripts/vendor.mjs from plugin.json. Do not edit.\nexport const CLIENT_VERSION = '${manifest.version}' as const\n`,
)
