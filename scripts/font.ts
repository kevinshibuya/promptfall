// Builds plugins/promptfall/hooks/windows/glyphs.ts from art/fonts/misaki_gothic_2nd.ttf (grill
// 1.18): each character's full-width form, 8 × 8 at 8 px per em, placed at rows GLYPH_Y.. of an
// 8 × 16 cell, plus the hand-drawn ▶ ▼ ▾ of docs/design/ui-remake/transcription.md. A pure
// function of committed input: `pnpm font:check` fails CI when the committed module is stale.
//
// tsx scripts/font.ts
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import opentype from 'opentype.js'

export const GLYPH_W = 8
export const GLYPH_H = 16
/** The 8 × 8 glyph's first row in the 16-row cell: DQ V's type sits at rows 5-11 (transcription). */
export const GLYPH_Y = 5
const PX = 8

/** What `bakeGlyph` reads of an opentype.js Font. */
type Font = {
  unitsPerEm: number
  ascender: number
  charToGlyph: (ch: string) => {
    index: number
    advanceWidth?: number
    path?: { commands: { type: string; x?: number; y?: number }[] }
  }
}

/** Printable ASCII, then the marks the windows write that ASCII lacks (≤: a buy order's cap). */
export const SET = [
  ...Array.from({ length: 0x7f - 0x20 }, (_, i) => String.fromCharCode(0x20 + i)),
  '·',
  '…',
  '≤',
]

/** The font character each baked character is drawn from. */
function source(ch: string): string {
  if (ch === '·') return '・'
  if (ch === '≤') return '≦'
  const code = ch.charCodeAt(0)
  if (code >= 0x21 && code <= 0x7e) return String.fromCharCode(code + 0xfee0)
  return ch
}

/** Hand-drawn cells, `#` on (transcription.md, "Bitmaps"). */
const HAND: Record<string, string[]> = {
  '▶': ['..#.....', '..##....', '..###...', '..####..', '..###...', '..##....', '..#.....'],
  '▼': ['#######.', '.#####..', '..###...', '...#....'],
  '▾': ['.#####..', '..###...', '...#....'],
}
const HAND_TOP: Record<string, number> = { '▶': 5, '▼': 6, '▾': 7 }

function handGlyph(ch: string): Uint8Array {
  const out = new Uint8Array(GLYPH_H)
  const top = HAND_TOP[ch] ?? 0
  for (const [i, row] of (HAND[ch] ?? []).entries()) {
    let bits = 0
    for (let x = 0; x < GLYPH_W; x++) if (row[x] === '#') bits |= 0x80 >> x
    out[top + i] = bits
  }
  return out
}

/** Nonzero winding of the point against closed polygons made of line segments. */
function inside(polys: [number, number][][], x: number, y: number): boolean {
  let wind = 0
  for (const poly of polys) {
    for (let i = 0; i < poly.length; i++) {
      const [x0, y0] = poly[i] as [number, number]
      const [x1, y1] = poly[(i + 1) % poly.length] as [number, number]
      if (y0 <= y) {
        if (y1 > y && (x1 - x0) * (y - y0) - (x - x0) * (y1 - y0) > 0) wind += 1
      } else if (y1 <= y && (x1 - x0) * (y - y0) - (x - x0) * (y1 - y0) < 0) wind -= 1
    }
  }
  return wind !== 0
}

/** One character's 16 row bytes, bit 7 the leftmost pixel. Throws, naming it, on a bad glyph. */
export function bakeGlyph(font: Font, ch: string): Uint8Array {
  if (HAND[ch]) return handGlyph(ch)
  const out = new Uint8Array(GLYPH_H)
  if (ch === ' ') return out
  const unit = font.unitsPerEm / PX
  const g = font.charToGlyph(source(ch))
  if (!g || g.index === 0 || !g.path) throw new Error(`font: no glyph for ${JSON.stringify(ch)}`)
  if (g.advanceWidth !== PX * unit)
    throw new Error(
      `font: ${JSON.stringify(ch)} advances ${(g.advanceWidth ?? 0) / unit} px, not ${PX}`,
    )
  const polys: [number, number][][] = []
  let poly: [number, number][] = []
  for (const c of g.path.commands) {
    if (c.type === 'Z') {
      if (poly.length) polys.push(poly)
      poly = []
      continue
    }
    if (c.type !== 'M' && c.type !== 'L')
      throw new Error(`font: ${JSON.stringify(ch)} has a curve (${c.type}); expected pixel squares`)
    const x = c.x ?? 0
    const y = c.y ?? 0
    if (x % unit !== 0 || y % unit !== 0)
      throw new Error(`font: ${JSON.stringify(ch)} has a point off the pixel grid (${x}, ${y})`)
    if (c.type === 'M' && poly.length) {
      polys.push(poly)
      poly = []
    }
    poly.push([x, y])
  }
  if (poly.length) polys.push(poly)
  for (let py = 0; py < PX; py++) {
    let bits = 0
    for (let px = 0; px < PX; px++) {
      const ux = (px + 0.5) * unit
      const uy = font.ascender - (py + 0.5) * unit
      if (inside(polys, ux, uy)) bits |= 0x80 >> px
    }
    out[GLYPH_Y + py] = bits
  }
  return out
}

export function buildGlyphs(font: Font): Map<string, Uint8Array> {
  const out = new Map<string, Uint8Array>()
  for (const ch of [...SET, ...Object.keys(HAND)]) out.set(ch, bakeGlyph(font, ch))
  return out
}

/** Rows as `#`/`.` strings, for tests and eyeballing. */
export function rowsOf(glyph: Uint8Array): string[] {
  return [...glyph].map((b) =>
    Array.from({ length: GLYPH_W }, (_, x) => (b & (0x80 >> x) ? '#' : '.')).join(''),
  )
}

export function emitModule(glyphs: Map<string, Uint8Array>): string {
  const lines = [
    '// Generated by scripts/font.ts from art/fonts/misaki_gothic_2nd.ttf. Do not edit: run `pnpm font`.',
    '// Glyph bitmaps derived from the Misaki font by Num Kadoma (see NOTICE.md).',
    '',
    `export const GLYPH_W = ${GLYPH_W}`,
    `export const GLYPH_H = ${GLYPH_H}`,
    '',
    '/** 16 rows of 8 bits per character, as 32 hex digits; bit 7 of each row is the leftmost pixel. */',
    'const HEX: Record<string, string> = {',
  ]
  for (const [ch, g] of glyphs) {
    const hex = [...g].map((b) => b.toString(16).padStart(2, '0')).join('')
    lines.push(`  ${JSON.stringify(ch)}: '${hex}',`)
  }
  lines.push(
    '}',
    '',
    'const cache = new Map<string, Uint8Array>()',
    '',
    '/** The 16 row bytes of `ch`, or null for a character not in the set. */',
    'export function glyph(ch: string): Uint8Array | null {',
    '  const hit = cache.get(ch)',
    '  if (hit) return hit',
    '  const hex = HEX[ch]',
    '  if (hex === undefined) return null',
    '  const rows = new Uint8Array(GLYPH_H)',
    '  for (let i = 0; i < GLYPH_H; i++) rows[i] = Number.parseInt(hex.slice(i * 2, i * 2 + 2), 16)',
    '  cache.set(ch, rows)',
    '  return rows',
    '}',
    '',
  )
  return lines.join('\n')
}

export function loadFont(path: string): Font {
  const buf = readFileSync(path)
  return opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength)) as Font
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  const root = join(import.meta.dirname, '..')
  const font = loadFont(join(root, 'art/fonts/misaki_gothic_2nd.ttf'))
  const out = join(root, 'plugins/promptfall/hooks/windows/glyphs.ts')
  writeFileSync(out, emitModule(buildGlyphs(font)))
  console.log(`${out}: ${SET.length + Object.keys(HAND).length} glyphs`)
}
